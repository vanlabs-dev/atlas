"""The claims ledger, `grounding/claims.yaml` (change: chain-grounding).

One claim is one plain sentence about how the chain works, with evidence
(a path and line range at a tag) and the source paths whose change would
affect it. The job marks claims stale from a tag diff, re-verifies only
those, and renders GROUNDING.md from the ledger.

Claim fields: id, section, statement, evidence, live_since_spec, status
(live | pending | deprecated), last_verified (UTC), watched_paths. The job
adds: stale (bool), review (null, or the UNVERIFIED record with the
proposed text and the reason), item and default (hyperparameter claims),
deprecated_since_spec (deprecated claims).
"""

from __future__ import annotations

import fnmatch
import os
import re
from typing import Any, Dict, Iterable, List, Optional

import yamlsub

HEADER = ("Generated by grounding/atlas_grounding.py. Do not edit by hand:\n"
          "use `python3 grounding/atlas_grounding.py review` (see "
          "grounding/README.md).\nGROUNDING.md is rendered from this file.")
STATUSES = ("live", "pending", "deprecated")
UNVERIFIED = "UNVERIFIED (pending review)"
ID_RE = re.compile(r"^([a-z]+)-(\d{3})$")
META_KEYS = ("spec_version", "subtensor_tag", "subtensor_commit",
             "newest_tag", "newest_tag_live", "last_updated",
             "content_changed", "content_hash", "pending_on_main",
             "verified_through", "queued_items", "changelog",
             "spec_dates")


def empty() -> Dict[str, Any]:
    return {"version": 1, "meta": {key: None for key in META_KEYS},
            "claims": []}


def load(path: str) -> Dict[str, Any]:
    try:
        with open(path, "r", encoding="utf-8") as handle:
            data = yamlsub.load(handle.read())
    except FileNotFoundError:
        return empty()
    validate(data)
    return data


def dump(data: Dict[str, Any]) -> str:
    validate(data)
    return yamlsub.dump(data, HEADER)


def save(path: str, data: Dict[str, Any]) -> None:
    text = dump(data)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp, path)


def validate(data: Dict[str, Any]) -> None:
    """Raise ValueError on any shape the job would not write."""
    if data.get("version") != 1 or not isinstance(data.get("claims"), list):
        raise ValueError("claims.yaml: version 1 with a claims list expected")
    meta = data.get("meta")
    if not isinstance(meta, dict):
        raise ValueError("claims.yaml: meta mapping expected")
    seen = set()
    for claim in data["claims"]:
        cid = claim.get("id")
        if not isinstance(cid, str) or not ID_RE.match(cid):
            raise ValueError("claim id %r is not <section>-<nnn>" % (cid,))
        if cid in seen:
            raise ValueError("duplicate claim id %s" % cid)
        seen.add(cid)
        if ID_RE.match(cid).group(1) != claim.get("section"):
            raise ValueError("claim %s is not in section %s" % (
                cid, claim.get("section")))
        if claim.get("status") not in STATUSES:
            raise ValueError("claim %s: status %r" % (cid,
                                                      claim.get("status")))
        if not isinstance(claim.get("statement"), str):
            raise ValueError("claim %s: no statement" % cid)
        for ev in claim.get("evidence") or []:
            for key in ("path", "lines", "ref", "commit"):
                if not isinstance(ev.get(key), str):
                    raise ValueError("claim %s: evidence without %s" % (
                        cid, key))
        if not isinstance(claim.get("watched_paths"), list):
            raise ValueError("claim %s: watched_paths list expected" % cid)


def by_section(data: Dict[str, Any], section: str) -> List[Dict[str, Any]]:
    return [c for c in data["claims"] if c["section"] == section]


def find(data: Dict[str, Any], cid: str) -> Optional[Dict[str, Any]]:
    for claim in data["claims"]:
        if claim["id"] == cid:
            return claim
    return None


def next_id(data: Dict[str, Any], section: str) -> str:
    used = [int(ID_RE.match(c["id"]).group(2)) for c in data["claims"]
            if c["section"] == section]
    return "%s-%03d" % (section, max(used or [0]) + 1)


def watches(pattern: str, path: str) -> bool:
    """A watched path matches a changed file: a directory prefix (ending
    in /), an exact file, or a glob."""
    pattern = pattern.strip()
    if not pattern:
        return False
    if pattern.endswith("/"):
        return path.startswith(pattern)
    if any(ch in pattern for ch in "*?["):
        return fnmatch.fnmatchcase(path, pattern)
    return path == pattern


def mark_stale(data: Dict[str, Any], changed: Iterable[str]) -> List[str]:
    """Mark every claim stale whose watched paths, or whose evidence
    paths, match a changed file. Returns the ids newly marked."""
    changed = list(changed)
    marked = []
    for claim in data["claims"]:
        if claim.get("stale"):
            continue
        patterns = list(claim.get("watched_paths") or []) + [
            ev["path"] for ev in claim.get("evidence") or []]
        if any(watches(p, f) for p in patterns for f in changed):
            claim["stale"] = True
            marked.append(claim["id"])
    return marked


def route_items(names: Iterable[str],
                keywords: List[List[Any]]) -> Dict[str, List[str]]:
    """Section for each new extrinsic or storage item, by the first
    keyword list that matches its name; `hyperparameters` otherwise."""
    routed: Dict[str, List[str]] = {}
    for name in names:
        target = "hyperparameters"
        for section, words in keywords:
            if any(word.lower() in name.lower() for word in words):
                target = section
                break
        routed.setdefault(target, []).append(name)
    return routed


def stale_sections(data: Dict[str, Any]) -> List[str]:
    """Sections with stale claims or queued new items, in ledger order."""
    out: List[str] = []
    queued = data["meta"].get("queued_items") or {}
    for claim in data["claims"]:
        if claim.get("stale") and claim["section"] not in out:
            out.append(claim["section"])
    for section in queued:
        if section not in out:
            out.append(section)
    return out
